# ============================================================================
#  webhook.sh — push-to-deploy: GitHub webhook -> deploy.php -> git reset.
#
#  Layout note: the tiny receiver (deploy-<hex>.php) must be web-accessible,
#  so it goes into the web root next to the project. The SECRET and full
#  config live OUTSIDE the web root in ~/.cpanel-deploy/<slug>/ (mode 600).
#  `git reset --hard` only touches TRACKED files, so the receiver file —
#  untracked — is never disturbed by deploys.
# ============================================================================

# webhook_install — requires SLUG, REPO_PATH, BRANCH from cmd_start.
# Sets WEBHOOK_SECRET, WEBHOOK_PHP, INI_FILE, LOCK_FILE, DEPLOY_LOG.
# Returns 1 when the project is not inside the web root (webhook impossible).
webhook_install() {
  local _docroot="$HOME/public_html" _dir _hex
  case "$REPO_PATH" in
    "$_docroot"|"$_docroot"/*) : ;;
    *) return 1 ;;
  esac
  ensure_state_dir
  _dir="$DEPLOY_STATE_DIR/$SLUG"
  _hex=$(gen_hex 4)
  WEBHOOK_SECRET=$(gen_hex 32)
  WEBHOOK_PHP="$_docroot/deploy-$_hex.php"
  INI_FILE="$_dir/deploy.ini"
  LOCK_FILE="$_dir/deploy.lock"
  DEPLOY_LOG="$_dir/deploy.log"

  if [ "${DRY_RUN:-0}" = "1" ]; then
    dim "[dry-run] write receiver config $INI_FILE (mode 600)"
    dim "[dry-run] write web receiver  $WEBHOOK_PHP"
    return 0
  fi

  ( umask 077
    {
      printf 'repo_path="%s"\n' "$REPO_PATH"
      printf 'branch="%s"\n' "$BRANCH"
      printf 'secret="%s"\n' "$WEBHOOK_SECRET"
      printf 'log_file="%s"\n' "$DEPLOY_LOG"
      printf 'lock_file="%s"\n' "$LOCK_FILE"
      printf 'after_cmd="%s"\n' "${AFTER_CMD:-}"
    } > "$INI_FILE"
  )

  sed "s|{{CONF_FILE}}|$INI_FILE|g" \
      "$REPO_TOOL_DIR/templates/deploy.php.tpl" > "$WEBHOOK_PHP"
  chmod 644 "$WEBHOOK_PHP"

  ok "Webhook receiver installed: $WEBHOOK_PHP"
  ok "Receiver secret stored outside the web root: $INI_FILE (mode 600)"
  return 0
}

# cron_install — writes pull-cron.sh for cPanel -> Cron Jobs (fallback mode).
# Sets CRON_SH. Runs as the cPanel user, no root needed.
cron_install() {
  ensure_state_dir
  local _dir="$DEPLOY_STATE_DIR/$SLUG"
  CRON_SH="$_dir/pull-cron.sh"

  if [ "${DRY_RUN:-0}" = "1" ]; then
    dim "[dry-run] write cron pull script $CRON_SH"
    return 0
  fi

  cat > "$CRON_SH" <<CRONEOF
#!/usr/bin/env bash
# Auto-generated by gitship (\`repo start\`) for project $SLUG.
# SELF-CONTAINED: all values are baked in below, so this script keeps working
# even if the gitship tool is later removed. Safe to run often: exits
# quickly when nothing changed and skips if a pull is already running.
REPO_PATH='$REPO_PATH'
BRANCH='$BRANCH'
LOG_FILE='$DEPLOY_LOG'
LOCK_DIR='$LOCK_FILE.dir'
[ -d "\$REPO_PATH/.git" ] || exit 0
if ! mkdir "\$LOCK_DIR" 2>/dev/null; then
  exit 0
fi
trap 'rmdir "\$LOCK_DIR" 2>/dev/null' EXIT
printf '[%s] cron check\n' "\$(date '+%Y-%m-%d %H:%M:%S')" >> "\$LOG_FILE"
cd "\$REPO_PATH" || exit 0
git fetch origin "\$BRANCH" >>"\$LOG_FILE" 2>&1 || exit 0
if ! git diff --quiet FETCH_HEAD HEAD 2>/dev/null; then
  if git reset --hard FETCH_HEAD >>"\$LOG_FILE" 2>&1; then
    printf '[%s] CRON DEPLOY OK\n' "\$(date '+%Y-%m-%d %H:%M:%S')" >> "\$LOG_FILE"
  fi
fi
CRONEOF
  chmod 700 "$CRON_SH"
  ok "Cron pull script installed: $CRON_SH"
  return 0
}
